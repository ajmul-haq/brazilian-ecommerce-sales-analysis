-- ============================================================
-- 01. TOTAL UNIQUE CUSTOMERS
-- Business Question:
-- How many unique customers placed orders?
--
-- Purpose:
-- Measure the total customer base and purchasing reach.
-- customer_unique_id identifies customers across orders.
-- ============================================================

SELECT
    COUNT(DISTINCT c.customer_unique_id)
        AS total_unique_customers,

    COUNT(DISTINCT o.order_id)
        AS total_orders,

    COUNT(DISTINCT o.customer_id)
        AS total_customer_order_records

FROM customers c
INNER JOIN orders o
    ON c.customer_id = o.customer_id;

-- ============================================================
-- 02. REPEAT CUSTOMER RATE
-- Business Question:
-- What percentage of customers placed more than one order?
--
-- Purpose:
-- Measure customer retention and repeat purchasing.
--
-- Formula:
-- Repeat Customer Rate =
-- Customers With More Than One Order
-- / Total Unique Customers * 100
-- ============================================================

WITH customer_orders AS (

    SELECT
        c.customer_unique_id,
        COUNT(DISTINCT o.order_id) AS total_orders

    FROM customers c
    INNER JOIN orders o
        ON c.customer_id = o.customer_id

    GROUP BY c.customer_unique_id

)

SELECT
    COUNT(*) AS total_unique_customers,

    COUNT(*) FILTER (
        WHERE total_orders > 1
    ) AS repeat_customers,

    COUNT(*) FILTER (
        WHERE total_orders = 1
    ) AS one_time_customers,

    ROUND(
        (
            COUNT(*) FILTER (
                WHERE total_orders > 1
            )::NUMERIC
            / NULLIF(COUNT(*), 0)
        ) * 100,
        2
    ) AS repeat_customer_percentage

FROM customer_orders;

-- ============================================================
-- 03. CUSTOMER DISTRIBUTION BY STATE
-- Business Question:
-- Which Brazilian states have the most unique customers?
--
-- Purpose:
-- Identify the strongest customer markets geographically.
-- ============================================================

SELECT
    c.customer_state,

    COUNT(
        DISTINCT c.customer_unique_id
    ) AS total_unique_customers,

    COUNT(
        DISTINCT o.order_id
    ) AS total_orders

FROM customers c
INNER JOIN orders o
    ON c.customer_id = o.customer_id

GROUP BY
    c.customer_state

ORDER BY
    total_unique_customers DESC

LIMIT 10;

-- ============================================================
-- 04. REVENUE GENERATED BY EACH CUSTOMER
-- Business Question:
-- How much sales value does each customer generate?
--
-- Purpose:
-- Identify high-value customers and purchasing patterns.
--
-- Note:
-- Product sales and freight are separate measures.
-- Revenue is based on order items, not payment records.
-- ============================================================

SELECT
    c.customer_unique_id,

    COUNT(
        DISTINCT o.order_id
    ) AS total_orders,

    ROUND(
        SUM(oi.price)::NUMERIC,
        2
    ) AS total_product_sales,

    ROUND(
        SUM(oi.freight_value)::NUMERIC,
        2
    ) AS total_freight_value,

    ROUND(
        SUM(
            oi.price + oi.freight_value
        )::NUMERIC,
        2
    ) AS total_sales_plus_freight,

    ROUND(
        (
            SUM(
                oi.price + oi.freight_value
            ) / NULLIF(
                COUNT(DISTINCT o.order_id),
                0
            )
        )::NUMERIC,
        2
    ) AS average_order_value

FROM customers c
INNER JOIN orders o
    ON c.customer_id = o.customer_id

INNER JOIN order_items oi
    ON o.order_id = oi.order_id

GROUP BY
    c.customer_unique_id

ORDER BY
    total_sales_plus_freight DESC

LIMIT 20;
-- ============================================================
-- 05. TIME BETWEEN CUSTOMER PURCHASES
-- Business Question:
-- How long does it take customers to place another order?
--
-- Purpose:
-- Understand repeat-purchase intervals and customer behavior.
--
-- Method:
-- Use LAG() to compare each order with the previous order.
-- ============================================================

WITH customer_purchase_history AS (

    SELECT
        c.customer_unique_id,
        o.order_id,
        o.order_purchase_timestamp,

        LAG(
            o.order_purchase_timestamp
        ) OVER (
            PARTITION BY c.customer_unique_id
            ORDER BY
                o.order_purchase_timestamp,
                o.order_id
        ) AS previous_order_timestamp

    FROM customers c
    INNER JOIN orders o
        ON c.customer_id = o.customer_id

)

SELECT
    customer_unique_id,

    order_id,

    previous_order_timestamp,

    order_purchase_timestamp
        AS current_order_timestamp,

    ROUND(
        (
            EXTRACT(
                EPOCH FROM (
                    order_purchase_timestamp
                    - previous_order_timestamp
                )
            ) / 86400.0
        )::NUMERIC,
        2
    ) AS days_between_orders

FROM customer_purchase_history

WHERE previous_order_timestamp IS NOT NULL

ORDER BY
    days_between_orders DESC;

-- ============================================================
-- 06. AVERAGE TIME BETWEEN REPEAT PURCHASES
-- Business Question:
-- What is the average interval between consecutive orders?
--
-- Purpose:
-- Estimate the typical time between repeat purchases.
-- Only customers with at least two orders are included.
-- ============================================================

WITH customer_purchase_history AS (

    SELECT
        c.customer_unique_id,

        o.order_purchase_timestamp,

        LAG(
            o.order_purchase_timestamp
        ) OVER (
            PARTITION BY c.customer_unique_id
            ORDER BY
                o.order_purchase_timestamp,
                o.order_id
        ) AS previous_order_timestamp

    FROM customers c
    INNER JOIN orders o
        ON c.customer_id = o.customer_id

),

purchase_intervals AS (

    SELECT
        EXTRACT(
            EPOCH FROM (
                order_purchase_timestamp
                - previous_order_timestamp
            )
        ) / 86400.0 AS days_between_orders

    FROM customer_purchase_history

    WHERE previous_order_timestamp IS NOT NULL

)

SELECT
    COUNT(*) AS total_repeat_purchase_intervals,

    ROUND(
        AVG(days_between_orders)::NUMERIC,
        2
    ) AS average_days_between_orders,

    ROUND(
        PERCENTILE_CONT(0.5)
        WITHIN GROUP (
            ORDER BY days_between_orders
        )::NUMERIC,
        2
    ) AS median_days_between_orders

FROM purchase_intervals;